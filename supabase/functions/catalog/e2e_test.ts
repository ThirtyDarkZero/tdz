// End-to-end test of the catalog function against a real Postgres (through
// PostgREST, like Supabase) with MusicBrainz and YouTube mocked.
// Run: CATALOG_E2E_DB=http://localhost:3901 deno test --allow-env --allow-net catalog/e2e_test.ts
import assert from "node:assert/strict";

const DB = Deno.env.get("CATALOG_E2E_DB");
const ytCalls: string[] = [];
const mbCalls: string[] = [];

const desc = (title: string, album: string, date: string) =>
  `Provided to YouTube by Republic Records\n\n${title} · Drake\n\n${album}\n\n℗ 2018 OVO\n\nReleased on: ${date}\n\nAuto-generated by YouTube.`;
const UPLOADS = [
  { id: "vSurvival", title: "Survival", d: desc("Survival", "Scorpion", "2018-06-29"), views: 50 },
  { id: "vNonstop", title: "Nonstop", d: desc("Nonstop", "Scorpion", "2018-06-29"), views: 300 },
  { id: "vGodsPlan", title: "God's Plan", d: desc("God's Plan", "Scorpion", "2018-06-29"), views: 9000 },
  { id: "vOneDance", title: "One Dance", d: desc("One Dance (feat. Wizkid & Kyla)", "Views", "2016-04-29"), views: 7000 },
  { id: "vHotline", title: "Hotline Bling", d: desc("Hotline Bling", "Hotline Bling", "2015-07-31"), views: 8000 },
  { id: "vScary1", title: "God's Plan (Scary Hours)", d: desc("Diplomatic Immunity", "Scary Hours", "2018-01-19"), views: 100 },
];
const MB_GROUPS = [
  { id: "00000000-0000-4000-8000-0000000000a1", title: "Scorpion", "primary-type": "Album", "first-release-date": "2018-06-29" },
  { id: "00000000-0000-4000-8000-0000000000a2", title: "Scorpion", "primary-type": "Album", "first-release-date": "2019-01-01" }, // duplicate
  { id: "00000000-0000-4000-8000-0000000000a3", title: "Views", "primary-type": "Album", "first-release-date": "2016-04-29" },
  { id: "00000000-0000-4000-8000-0000000000a4", title: "Hotline Bling", "primary-type": "Single", "first-release-date": "2015-07-31" },
  { id: "00000000-0000-4000-8000-0000000000a5", title: "Care Package", "primary-type": "Album", "secondary-types": ["Compilation"], "first-release-date": "2019-08-02" },
];

function mockExternal(url: URL): Response | null {
  const ok = (b: unknown) => new Response(JSON.stringify(b), { headers: { "Content-Type": "application/json" } });
  if (url.hostname === "musicbrainz.org") {
    mbCalls.push(url.pathname + url.search);
    if (url.pathname === "/ws/2/artist") {
      return ok({ artists: [
        { id: "00000000-0000-4000-8000-00000000d0d0", name: "Drake", score: 100, country: "CA", type: "Person",
          tags: [{ name: "hip hop", count: 9 }, { name: "rnb", count: 4 }] },
        { id: "00000000-0000-4000-8000-00000000be11", name: "Drake Bell", score: 95 },
      ] });
    }
    if (url.pathname === "/ws/2/release-group") return ok({ "release-group-count": MB_GROUPS.length, "release-groups": MB_GROUPS });
    if (url.pathname === "/ws/2/release") {
      return ok({ releases: [{ id: "r1", media: [{ format: "Digital Media", tracks: [
        { title: "Survival", length: 136000, recording: { id: "rec1" } },
        { title: "Nonstop", length: 238000, recording: { id: "rec2" } },
        { title: "God's Plan", length: 198000, recording: { id: "rec3" } },
        { title: "In My Feelings", length: 217000, recording: { id: "rec4" } },
      ] }] }] });
    }
    return new Response("not found", { status: 404 });
  }
  if (url.hostname === "www.googleapis.com") {
    const ep = url.pathname.split("/").pop()!;
    ytCalls.push(ep + (url.searchParams.get("type") ? `:${url.searchParams.get("type")}` : ""));
    if (ep === "search" && url.searchParams.get("type") === "channel") {
      return ok({ items: [
        { id: { channelId: "UCbell" }, snippet: { title: "Drake Bell - Topic" } },
        { id: { channelId: "UCdrake" }, snippet: { title: "Drake - Topic" } },
      ] });
    }
    if (ep === "channels") {
      return ok({ items: [{ contentDetails: { relatedPlaylists: { uploads: "UUdrake" } },
        snippet: { thumbnails: { high: { url: "https://yt3.example/drake.jpg" } } } }] });
    }
    if (ep === "playlistItems") {
      const page2 = url.searchParams.get("pageToken") === "p2";
      const items = (page2 ? UPLOADS.slice(3) : UPLOADS.slice(0, 3)).map((u) => ({
        snippet: { title: u.title, description: u.d, resourceId: { videoId: u.id } },
      }));
      return ok({ items, ...(page2 ? {} : { nextPageToken: "p2" }) });
    }
    if (ep === "videos") {
      const ids = url.searchParams.get("id")!.split(",");
      return ok({ items: ids.map((id) => ({ id, contentDetails: { duration: "PT3M30S" },
        statistics: { viewCount: String(UPLOADS.find((u) => u.id === id)!.views) } })) });
    }
    if (ep === "search" && url.searchParams.get("type") === "video") {
      return ok({ items: [
        { id: { videoId: "vFanCover" }, snippet: { title: "In My Feelings (cover)", channelTitle: "Some Fan" } },
        { id: { videoId: "vInMyFeelings" }, snippet: { title: "In My Feelings", channelTitle: "Drake - Topic" } },
      ] });
    }
  }
  return null;
}

Deno.test({
  name: "catalog builds a playable artist profile once and serves it from the database",
  ignore: !DB,
  sanitizeOps: false,
  sanitizeResources: false,
  async fn() {
    Deno.env.set("SUPABASE_URL", "http://supabase.test");
    Deno.env.set("SUPABASE_SERVICE_ROLE_KEY", "test");
    Deno.env.set("YOUTUBE_API_KEY", "test-key");
    const realFetch = globalThis.fetch;
    globalThis.fetch = ((input: RequestInfo | URL, init?: RequestInit) => {
      const url = new URL(typeof input === "string" ? input : input instanceof URL ? input.href : input.url);
      if (url.hostname === "supabase.test") {
        const headers = new Headers(init?.headers ?? (input instanceof Request ? input.headers : undefined));
        headers.delete("Authorization");
        const target = `${DB}${url.pathname.replace(/^\/rest\/v1/, "")}${url.search}`;
        return realFetch(target, { ...init, headers, method: init?.method ?? (input instanceof Request ? input.method : "GET"),
          body: init?.body ?? (input instanceof Request ? input.body : undefined) });
      }
      const mocked = mockExternal(url);
      if (mocked) return Promise.resolve(mocked);
      return Promise.reject(new Error(`unexpected network call ${url}`));
    }) as typeof fetch;

    const unitsUsed = async () =>
      ((await (await realFetch(`${DB}/catalog_api_usage`)).json()) as Array<{ units: number }>)
        .reduce((n, r) => n + r.units, 0);
    const unitsAtStart = await unitsUsed();

    let handler: ((req: Request) => Promise<Response>) | null = null;
    // deno-lint-ignore no-explicit-any
    (Deno as any).serve = (h: (req: Request) => Promise<Response>) => { handler = h; };
    await import("./index.ts");
    const call = async (body: unknown) => {
      const res = await handler!(new Request("http://fn/catalog", { method: "POST", body: JSON.stringify(body),
        headers: { "cf-connecting-ip": "203.0.113.9" } }));
      return { status: res.status, body: await res.json() };
    };

    // First visit: builds the profile.
    const first = await call({ action: "artist", name: "drake" });
    assert.equal(first.status, 200, JSON.stringify(first.body));
    const { artist, releases, topTracks } = first.body;
    assert.equal(artist.name, "Drake");
    assert.equal(artist.status, "ready");
    assert.equal(artist.youtube_channel_id, "UCdrake", "picked Drake's Topic channel, not Drake Bell's");
    assert.equal(artist.image_url, "https://yt3.example/drake.jpg");
    assert.equal(artist.tdz_user_id, "11111111-1111-4111-8111-111111111111", "linked to the TDZ artist");
    assert.deepEqual(artist.genres, ["hip hop", "rnb"]);

    const byTitle = Object.fromEntries(releases.map((r: { title: string }) => [r.title, r]));
    assert.equal(releases.filter((r: { title: string }) => r.title === "Scorpion").length, 1, "duplicate edition collapsed");
    assert.equal(byTitle["Scorpion"].release_type, "album");
    assert.equal(byTitle["Scorpion"].playable_tracks, 3);
    assert.equal(byTitle["Hotline Bling"].release_type, "single");
    assert.equal(byTitle["Care Package"].release_type, "compilation");
    assert.equal(byTitle["Scary Hours"].release_type, "single", "YouTube-only release kept");
    assert.equal(byTitle["Views"].playable_tracks, 1);
    assert.deepEqual(topTracks.slice(0, 3).map((t: { youtube_id: string }) => t.youtube_id), ["vGodsPlan", "vHotline", "vOneDance"]);
    assert.equal(topTracks[0].duration_sec, 210);
    assert.deepEqual(ytCalls, ["search:channel", "channels", "playlistItems", "playlistItems", "videos"]);

    // Album page: official order, matched videos, a gap for the song YouTube didn't have.
    // Three visitors open the new album at the same moment: the tracklist is saved once.
    const [album] = await Promise.all([1, 2, 3].map(() => call({ action: "release", id: byTitle["Scorpion"].id })));
    assert.equal(album.status, 200);
    assert.deepEqual(album.body.tracks.map((t: { title: string }) => t.title), ["Survival", "Nonstop", "God's Plan", "In My Feelings"]);
    assert.deepEqual(album.body.tracks.map((t: { youtube_id: string | null }) => t.youtube_id), ["vSurvival", "vNonstop", "vGodsPlan", null]);

    // Playing the missing song finds the official upload once, then remembers it.
    const missing = album.body.tracks[3];
    const play = await call({ action: "play", trackId: missing.id });
    assert.equal(play.body.youtube_id, "vInMyFeelings", "prefers the artist's Topic upload over a fan cover");
    const ytBefore = ytCalls.length;
    const again = await call({ action: "play", trackId: missing.id });
    assert.equal(again.body.youtube_id, "vInMyFeelings");
    assert.equal(ytCalls.length, ytBefore, "second play costs no YouTube quota");

    // Second visit: served from the database, no outside calls.
    const mbBefore = mbCalls.length;
    const second = await call({ action: "artist", name: "Drake" });
    assert.equal(second.body.artist.id, artist.id);
    assert.equal(mbCalls.length, mbBefore, "no MusicBrainz calls on repeat visits");
    assert.equal(ytCalls.length, ytBefore, "no YouTube calls on repeat visits");

    // Search finds the saved artist and the TDZ artist.
    const found = await call({ action: "search", query: "dra" });
    assert.equal(found.body.catalog[0].name, "Drake");
    assert.equal(found.body.tdz[0].artist_name, "Drake");

    // Whole first visit + one lookup = ~205 YouTube units (was ~500-800 per page view).
    assert.equal(await unitsUsed() - unitsAtStart, 100 + 1 + 1 + 1 + 1 + 100);
  },
});
