import assert from "node:assert/strict";
import {
  bestVideoForTitle, cleanVideoTitle, isoDurationToSeconds, isTopicChannelFor, normName, normRelease,
  normTrack, parseTopicDescription, pickMBArtist, releaseTypeFromCount, releaseTypeFromMB,
} from "./lib.ts";

Deno.test("artist names match across sources", () => {
  assert.equal(normName("Beyoncé"), normName("beyonce"));
  assert.equal(normName("Simon & Garfunkel"), normName("Simon and Garfunkel"));
  assert.equal(normName("The Weeknd"), normName("Weeknd"));
  assert.equal(normName("JAY-Z"), normName("Jay Z"));
});

Deno.test("release editions match the original", () => {
  assert.equal(normRelease("Scorpion (Deluxe Edition)"), normRelease("Scorpion"));
  assert.equal(normRelease("Abbey Road [2019 Remaster]"), normRelease("Abbey Road"));
  assert.equal(normRelease("Hotline Bling - Single"), normRelease("Hotline Bling"));
  assert.notEqual(normRelease("Scorpion"), normRelease("Views"));
});

Deno.test("track titles ignore features and video labels", () => {
  assert.equal(normTrack("Work (feat. Drake)"), normTrack("Work"));
  assert.equal(normTrack("Sicko Mode (Official Video)"), normTrack("SICKO MODE"));
  assert.equal(normTrack("Here Comes The Sun - Remastered 2019"), normTrack("Here Comes the Sun"));
  assert.equal(normTrack("Nice For What ft. Lil Wayne"), normTrack("Nice for What"));
});

Deno.test("video titles drop the artist prefix and labels", () => {
  assert.equal(cleanVideoTitle("Drake - God's Plan (Official Video)", "Drake"), "God's Plan");
  assert.equal(cleanVideoTitle("God's Plan", "Drake"), "God's Plan");
});

Deno.test("parses YouTube auto-generated track descriptions", () => {
  const d = `Provided to YouTube by Republic Records

God's Plan · Drake

Scorpion

℗ 2018 Young Money/Cash Money Records

Released on: 2018-06-29

Producer: Cardo
Composer Lyricist: Aubrey Graham

Auto-generated by YouTube.`;
  assert.deepEqual(parseTopicDescription(d), {
    title: "God's Plan", artists: ["Drake"], album: "Scorpion", releaseDate: "2018-06-29",
  });
});

Deno.test("parses multi-artist lines and tolerates missing album", () => {
  const d = "Provided to YouTube by X\n\nWork · Rihanna · Drake\n\n℗ 2016 Westbury Road\n\nReleased on: 2016-01-28";
  const p = parseTopicDescription(d)!;
  assert.equal(p.title, "Work");
  assert.deepEqual(p.artists, ["Rihanna", "Drake"]);
  assert.equal(p.album, null);
});

Deno.test("non auto-generated descriptions are ignored", () => {
  assert.equal(parseTopicDescription("Official video for God's Plan. Stream now!"), null);
  assert.equal(parseTopicDescription(null), null);
});

Deno.test("release types", () => {
  assert.equal(releaseTypeFromMB("Album"), "album");
  assert.equal(releaseTypeFromMB("Album", ["Compilation"]), "compilation");
  assert.equal(releaseTypeFromMB("Album", ["Live"]), "live");
  assert.equal(releaseTypeFromMB("Single"), "single");
  assert.equal(releaseTypeFromMB("EP"), "ep");
  assert.equal(releaseTypeFromMB(null), "other");
  assert.equal(releaseTypeFromCount(1), "single");
  assert.equal(releaseTypeFromCount(5), "ep");
  assert.equal(releaseTypeFromCount(14), "album");
});

Deno.test("durations", () => {
  assert.equal(isoDurationToSeconds("PT3M21S"), 201);
  assert.equal(isoDurationToSeconds("PT1H2M"), 3720);
  assert.equal(isoDurationToSeconds("PT45S"), 45);
  assert.equal(isoDurationToSeconds(undefined), null);
});

Deno.test("picks the right MusicBrainz artist", () => {
  const hits = [
    { id: "a", name: "Drake Bell", score: 100 },
    { id: "b", name: "Drake", score: 98, country: "CA" },
    { id: "c", name: "Drake", score: 60, disambiguation: "UK band" },
  ];
  assert.equal(pickMBArtist(hits, "Drake")!.id, "b");
  assert.equal(pickMBArtist([{ id: "x", name: "Prince", score: 80 }], "Unknown Name"), null);
  assert.equal(pickMBArtist([{ id: "y", name: "Ye", score: 70, aliases: [{ name: "Kanye West" }] }], "Kanye West")!.id, "y");
});

Deno.test("recognises the artist's Topic channel only", () => {
  assert.ok(isTopicChannelFor("Drake - Topic", "Drake"));
  assert.ok(isTopicChannelFor("Beyoncé - Topic", "Beyonce"));
  assert.ok(!isTopicChannelFor("Drake Bell - Topic", "Drake"));
  assert.ok(!isTopicChannelFor("DrakeVEVO", "Drake"));
});

Deno.test("matches a song to the most-viewed video with the same title", () => {
  const vids = [
    { id: 1, norm_title: normTrack("God's Plan"), view_count: 10 },
    { id: 2, norm_title: normTrack("God's Plan (Official Video)"), view_count: 900 },
    { id: 3, norm_title: normTrack("Nonstop"), view_count: 5000 },
  ];
  assert.equal(bestVideoForTitle(vids, "God's Plan")!.id, 2);
  assert.equal(bestVideoForTitle(vids, "In My Feelings"), null);
});
